package net.royalur.cli;

/**
 * The different rule types that can be used for games.
 */
public enum RuleType {
    /**
     * Finkel rules - the standard rules used by most players.
     */
    FINKEL,

    /**
     * Blitz rules - fast-paced variant.
     */
    BLITZ,

    /**
     * Masters rules - tournament style rules.
     */
    MASTERS
}
